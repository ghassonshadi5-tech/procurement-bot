"""
Invite Service - Business logic for managing company invitations.
Aligned with Procurement Bot Architecture v3.0 and Schema v2.0.

Replaces the old role_invite_codes system with token-based invitations
linked to specific roles, with expiration and single-use acceptance.

Security:
- Tokens are generated by PostgreSQL using gen_random_bytes(24) (48 hex chars).
- Tokens are cryptographically secure and unpredictable.
- Expired or accepted invitations cannot be reused.

CHANGE LOG:
- Assign UserRole inside accept_invitation (was left to caller — security risk).
- Use is_(None) instead of == None (SQLAlchemy 2.0 best practice).
"""
from datetime import datetime, timedelta, timezone
from typing import Optional, List, Tuple

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.database.database import get_session
from app.database.models.company_invitation import CompanyInvitation
from app.database.models.role import Role
from app.database.models.user import User
from app.database.models.user_role import UserRole
from app.core.logger import get_logger

logger = get_logger(__name__)


# Default invitation validity: 7 days
DEFAULT_INVITATION_VALIDITY_HOURS = 168  # 7 days


class InviteService:
    """
    Service class for Company Invitation operations.
    """

    @staticmethod
    async def create_invitation(
        company_id: int,
        role_code: str,
        created_by_user_id: int,
        validity_hours: int = DEFAULT_INVITATION_VALIDITY_HOURS,
    ) -> Optional[CompanyInvitation]:
        """
        Create a new invitation for a user to join a company with a specific role.

        The token is auto-generated by PostgreSQL via:
            DEFAULT encode(gen_random_bytes(24), 'hex')

        Args:
            company_id: The company to invite the user to.
            role_code: The role code to grant (e.g., 'manager', 'accountant').
            created_by_user_id: Kept for API compatibility; not persisted
                (the CompanyInvitation model has no `created_by` column).
            validity_hours: How long the invitation is valid (default: 7 days).

        Returns:
            The created CompanyInvitation object, or None if role doesn't exist.
        """
        async with get_session(company_id=company_id) as session:
            # Find the role
            stmt = select(Role).where(Role.code == role_code)
            result = await session.execute(stmt)
            role = result.scalar_one_or_none()

            if not role:
                logger.warning(
                    "Attempted to create invitation for non-existent role | role_code=%s",
                    role_code,
                )
                return None

            expires_at = datetime.now(timezone.utc) + timedelta(hours=validity_hours)

            invitation = CompanyInvitation(
                company_id=company_id,
                role_id=role.id,
                expires_at=expires_at,
            )

            session.add(invitation)
            await session.commit()
            await session.refresh(invitation)

            logger.info(
                "Created invitation | company_id=%s | role=%s | expires_at=%s | by_user=%s",
                company_id,
                role_code,
                expires_at.isoformat(),
                created_by_user_id,
            )
            return invitation

    @staticmethod
    async def validate_invitation(
        token: str,
    ) -> Tuple[bool, Optional[CompanyInvitation], Optional[str]]:
        """
        Validate an invitation token without consuming it.

        Checks:
        1. Token exists
        2. Not already accepted
        3. Not expired

        Args:
            token: The invitation token string.

        Returns:
            Tuple of (is_valid, invitation_object, error_message)
        """
        if not token or not token.strip():
            return False, None, "رمز الدعوة فارغ."

        token = token.strip().lower()

        async with get_session(silent=True) as session:
            stmt = select(CompanyInvitation).where(CompanyInvitation.token == token)
            result = await session.execute(stmt)
            invitation = result.scalar_one_or_none()

            if not invitation:
                return False, None, "رمز الدعوة غير صحيح."

            # Already accepted?
            if invitation.accepted_by is not None:
                return False, invitation, "هذا الرمز تم استخدامه بالفعل."

            # Expired?
            now = datetime.now(timezone.utc)
            if invitation.expires_at and invitation.expires_at < now:
                return False, invitation, "انتهت صلاحية رمز الدعوة."

            return True, invitation, None

    @staticmethod
    async def accept_invitation(
        token: str,
        user_id: int,
    ) -> Tuple[bool, Optional[CompanyInvitation], Optional[str]]:
        """
        Accept an invitation: link the user to the company, assign the role,
        and mark the invitation as accepted.

        This operation:
        1. Validates the token (exists, not accepted, not expired).
        2. Sets accepted_by and accepted_at on the invitation.
        3. Updates the user's company_id.
        4. Assigns the role via user_roles.

        Args:
            token: The invitation token.
            user_id: The ID of the user accepting the invitation.

        Returns:
            Tuple of (success, invitation_object, error_message)
        """
        token = token.strip().lower()

        async with get_session(silent=True) as session:
            # Find the invitation
            stmt = select(CompanyInvitation).where(CompanyInvitation.token == token)
            result = await session.execute(stmt)
            invitation = result.scalar_one_or_none()

            if not invitation:
                return False, None, "رمز الدعوة غير صحيح."

            # Already accepted?
            if invitation.accepted_by is not None:
                return False, invitation, "هذا الرمز تم استخدامه بالفعل."

            # Expired?
            now = datetime.now(timezone.utc)
            if invitation.expires_at and invitation.expires_at < now:
                return False, invitation, "انتهت صلاحية رمز الدعوة."

            # Find the user
            stmt = select(User).where(User.id == user_id)
            result = await session.execute(stmt)
            user = result.scalar_one_or_none()

            if not user:
                return False, invitation, "المستخدم غير موجود."

            # Check if user already belongs to a company or supplier
            if user.company_id is not None:
                return False, invitation, "أنت تنتمي بالفعل إلى شركة أخرى."
            if user.supplier_id is not None:
                return (
                    False,
                    invitation,
                    "أنت تنتمي بالفعل إلى مورد. لا يمكنك الانضمام إلى شركة.",
                )

            # Accept the invitation
            invitation.accepted_by = user_id
            invitation.accepted_at = now

            # Link user to company
            user.company_id = invitation.company_id

            # Assign role via user_roles
            user_role = UserRole(
                user_id=user_id,
                role_id=invitation.role_id,
            )
            session.add(user_role)

            await session.commit()
            await session.refresh(invitation)

            logger.info(
                "Invitation accepted | user_id=%s | company_id=%s | role_id=%s | token_prefix=%s",
                user_id,
                invitation.company_id,
                invitation.role_id,
                token[:8],
            )
            return True, invitation, None

    @staticmethod
    async def get_pending_invitations(company_id: int) -> List[CompanyInvitation]:
        """
        Get all pending (unused, unexpired) invitations for a company.
        Used by managers/owners to view and manage active invitations.
        """
        now = datetime.now(timezone.utc)
        async with get_session(company_id=company_id) as session:
            stmt = (
                select(CompanyInvitation)
                .where(
                    CompanyInvitation.company_id == company_id,
                    CompanyInvitation.accepted_by.is_(None),
                    CompanyInvitation.expires_at > now,
                )
                .order_by(CompanyInvitation.created_at.desc())
            )
            result = await session.execute(stmt)
            return list(result.scalars().all())

    @staticmethod
    async def get_invitation_by_token(token: str) -> Optional[CompanyInvitation]:
        """Fetch an invitation by its token (for deep-link handling)."""
        if not token:
            return None

        token = token.strip().lower()
        async with get_session(silent=True) as session:
            stmt = select(CompanyInvitation).where(CompanyInvitation.token == token)
            result = await session.execute(stmt)
            return result.scalar_one_or_none()


# Singleton instance for easy import
invite_service = InviteService()